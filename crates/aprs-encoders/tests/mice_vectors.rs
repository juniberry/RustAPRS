//! Mic-E golden vectors: inputs, the exact destination and information field
//! bytes, and what a decoder should read back. They come from an independent
//! integer implementation (the `uaprs` crate of the Ferrite firmware for the
//! Radtel RT-950 Pro) and cross-check this crate's encoder byte for byte, and
//! its decoder field by field, without a radio. Cases: the §10 worked
//! examples, every longitude fold in both hemispheres, all eight standard
//! messages, ambiguity 0–4, speed and course edges (0 = unknown course, 360 =
//! north, 799 knots), altitudes, status text that would be misread without
//! protection, and 179.99999°/180° longitude.

use aprs_core::MicEMessage;
use aprs_decoders::mice;
use aprs_encoders::mice::{encode_report, MicEInput};

pub struct Vector {
    latitude: f64,
    longitude: f64,
    speed_knots: u16,
    course: u16,
    message: MicEMessage,
    ambiguity: u8,
    altitude_feet: Option<i32>,
    status: &'static [u8],
    dest: &'static [u8; 6],
    info: &'static [u8],
    decoded_latitude: f64,
    decoded_longitude: f64,
    decoded_course: Option<u16>,
    decoded_altitude_feet: Option<i32>,
}

#[test]
fn encoder_matches_vectors() {
    for (i, v) in VECTORS.iter().enumerate() {
        let input = MicEInput {
            latitude: v.latitude,
            longitude: v.longitude,
            speed_knots: v.speed_knots,
            course: v.course,
            symbol_table: b'/',
            symbol_code: b'>',
            message: v.message,
            ambiguity: v.ambiguity,
            altitude_feet: v.altitude_feet,
            status: v.status,
        };
        let mut dest = [0u8; 6];
        let mut info = [0u8; 128];
        let (dl, il) = encode_report(&input, &mut dest, &mut info).unwrap();
        assert_eq!(&dest[..dl], v.dest, "vector {i}: destination");
        assert_eq!(&info[..il], v.info, "vector {i}: information field");
    }
}

#[test]
fn decoder_reads_vectors() {
    for (i, v) in VECTORS.iter().enumerate() {
        let p = mice::decode(v.dest, v.info).unwrap_or_else(|e| panic!("vector {i}: {e}"));
        assert!(
            (p.coordinates.latitude - v.decoded_latitude).abs() < 1e-9,
            "vector {i}: latitude {}",
            p.coordinates.latitude
        );
        assert!(
            (p.coordinates.longitude - v.decoded_longitude).abs() < 1e-9,
            "vector {i}: longitude {}",
            p.coordinates.longitude
        );
        assert_eq!(
            p.speed_knots,
            Some(v.speed_knots.min(799)),
            "vector {i}: speed"
        );
        assert_eq!(p.course, v.decoded_course, "vector {i}: course");
        assert_eq!(p.mic_e_message, Some(v.message), "vector {i}: message");
        assert_eq!(p.ambiguity, v.ambiguity, "vector {i}: ambiguity");
        assert_eq!(
            p.altitude_feet, v.decoded_altitude_feet,
            "vector {i}: altitude"
        );
        assert_eq!(p.symbol_code, b'>');
        // Protective leading spaces are the only difference allowed.
        assert_eq!(
            p.comment.trim_ascii_start(),
            v.status,
            "vector {i}: status text"
        );
        assert_eq!(p.device, None, "vector {i}: device");
    }
}

